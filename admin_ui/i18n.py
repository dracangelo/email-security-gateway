def get_translation(key: str, lang: str = "en") -> str:
    """Retrieve translated string for key and locale, falling back to English."""
    locale_dict = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    return locale_dict.get(key) or TRANSLATIONS["en"].get(key, key)


def get_translations_bundle(lang: str = "en") -> Dict[str, str]:
    """Retrieve complete dictionary bundle for the specified locale."""
    base = dict(TRANSLATIONS["en"])
    if lang in TRANSLATIONS and lang != "en":
        base.update(TRANSLATIONS[lang])
    return base


def get_all_translations() -> Dict[str, Dict[str, str]]:
    """Return all translations indexed by language code."""
    return TRANSLATIONS
